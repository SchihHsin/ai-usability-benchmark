"""Review-only rule amendments; no installed Skill mutation."""
def amend(D):
    support=[
      '有相关内容可评，但没有能用于任务的内容信息',
      '有背景、方向或零散操作，但未形成任何完整的关键操作或解释片段',
      '已有可用的关键操作或解释片段，但至少一项必需内容需要补建或重选支撑路径',
      '所有必需内容的支撑路径已形成，仅有可明确定位、无需改变路径的局部遗漏或错误',
      '全部题目要求的内容充分、前后一致，核对范围内未见实质缺口']
    versions=[
      '有相关资料/回答可评，但没有任何所需版本与配套信息',
      '仅列组件或版本名称、笼统建议，没有一条可用于选择的具体关系',
      '至少一条具体配套关系可用，但仍有必需关系缺失或需要重选、解决冲突',
      '全部必需关系的配套选择已明确，仅在题目要求的范围细节中有可定位的局部缺口',
      '全部题目要求的版本、范围和配套说明明确，未见影响适用性的未解决冲突']
    for d in D:
        k=d['id']
        if k in {'M3','M6','M11'}:
            d['bands']=support.copy()
            d['obs']=d['obs'].replace('核心/辅助','适用范围').replace('核心与辅助','全部适用')
            d['change']='统一五档；4分改为局部缺口' if k!='M11' else '联合支撑的范围调整，待确认'
            d['action']='先按原题固定必需内容及可观察的达成条件，再逐项核对。4分须指出缺口位置与局部补全方式；若还需选择新的关键方法、补建操作链路或补找一种核心解释，则属于3分边界。不能用字数、缺口数量或核心/辅助标签替代影响判断。没有辅助要求的任务也可出现4分。未知若影响档位则待定。'
            d['own']='五档是本研究拟定的有序量规，文献支持清楚描述、来源/回答分离和逐条核对，不直接验证档位。取消4分依赖辅助要求的设计；不把等级视为等距。'
            if 'RUBRIC' not in d['refs']:d['refs'].append('RUBRIC')
            d['example']='示意边界（非真实运行评分）：诊断的获取、定位、判读路径已说明，但输出字段名称有一个可明确纠正的笔误，可属4；若只说明去收集日志、缺少如何解释与继续定位的关键路径，则不能给4。'
        if k in {'M4','M9'}:
            d['bands']=versions.copy()
            d['action']='先按题目固定所需版本关系与范围，不添加题外要求。4分必须是既定选择无需改变、仅补全明确的范围细节；若关系本身不明、需要重新选择组件配套，属于3分或更低。明确却错误的关系不算可用。无版本需求为N/A，材料不足以判断时待定。'
            d['own']='关系清单与五档为研究设计；4分不再依赖辅助要求。IEEE文献当前只核对题录，不能作为这些细项的直接依据。'
        if k=='M1':
            d['obs']+=' 首次搜索超时、拒绝或未返回列表则M1未知；后续成功单列恢复。不将工具错误计为1分。'
        if k=='M7':
            d['obs']+=' 旧试跑的1—5自评不换算成概率；新旧表示不能混合。'
        if k=='M10':
            d['action']+=' 对4分同样要求指明局部修正位置和方式，不仅写“有少量问题”。'
    return D
